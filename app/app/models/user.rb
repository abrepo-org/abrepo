class User < ApplicationRecord
  has_many :subscriptions, dependent: :destroy
  has_many :user_saved_variations, dependent: :destroy
  has_many :variations, through: :user_saved_variations


  # Include default devise modules. Others available are:
  # :confirmable, :lockable, :timeoutable, :trackable and :omniauthable
  devise :database_authenticatable, :registerable,
         :recoverable, :rememberable, :validatable,
         :confirmable, :trackable, :timeoutable, :lockable


  def subscribed?
    self.subscriptions.pluck(:active).any?
  end

  def stripe_subscription
    begin
      stripe_subscription_id = self.subscriptions.last.stripe_subscription_id
      stripe_subscription = Stripe::Subscription.retrieve(stripe_subscription_id)
      return stripe_subscription
    rescue
      return nil
    end
  end
end
